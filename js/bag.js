/* ============================================================
   Cavalli Estates: Shop bag & product detail
   ------------------------------------------------------------
   Product data comes from <script id="shop-catalog"> in shop.html,
   generated by shop-data/build_shop.py. Cards open a detail view
   (photos, options, quantity); Add to Bag keeps a cart in
   localStorage. Checkout goes to Shopify when js/shop.js is
   configured, otherwise the bag is emailed to the estate.
   ============================================================ */
(function () {
  "use strict";

  var ORDER_EMAIL = "cavalli.estates@gmail.com";
  var KEY = "cavalli-bag";

  var catalogEl = document.getElementById("shop-catalog");
  var CATALOG = {};
  try { CATALOG = JSON.parse(catalogEl ? catalogEl.textContent : "{}"); } catch (e) {}

  function readBag() {
    try {
      return (JSON.parse(localStorage.getItem(KEY)) || []).filter(function (i) { return CATALOG[i.slug]; });
    } catch (e) { return []; }
  }
  function writeBag(items) {
    try { localStorage.setItem(KEY, JSON.stringify(items)); } catch (e) {}
    renderBadge();
  }
  function money(n) { return "$" + n.toFixed(2); }
  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    return n;
  }

  /* ---------- Collection filters ---------- */
  var filters = document.querySelectorAll(".shop-filter");
  filters.forEach(function (btn) {
    btn.addEventListener("click", function () {
      var f = btn.getAttribute("data-filter");
      filters.forEach(function (b) {
        var on = b === btn;
        b.classList.toggle("is-on", on);
        b.setAttribute("aria-pressed", on ? "true" : "false");
      });
      document.querySelectorAll(".products .product").forEach(function (card) {
        card.hidden = !(f === "all" || card.getAttribute("data-collection") === f);
      });
    });
  });

  /* ---------- Overlay skeletons ---------- */
  var overlay = el("div", "shop-overlay");
  overlay.innerHTML =
    '<div class="shop-overlay__scrim" data-close></div>' +
    '<div class="pmodal" role="dialog" aria-modal="true" aria-labelledby="pmodal-title">' +
    '  <button class="pmodal__close" type="button" data-close aria-label="Close">&times;</button>' +
    '  <div class="pmodal__media"><div class="pmodal__main"><img alt="" /></div><div class="pmodal__thumbs" data-m-thumbs></div></div>' +
    '  <div class="pmodal__body">' +
    '    <p class="eyebrow" data-m-tag></p>' +
    '    <h3 id="pmodal-title" data-m-name></h3>' +
    '    <p class="pmodal__price"><span data-m-subtotal></span></p>' +
    '    <div class="pmodal__opts" data-m-opts></div>' +
    '    <div class="pmodal__field"><label>Quantity</label>' +
    '      <div class="qty"><button type="button" data-qty-minus aria-label="Decrease">&minus;</button><span data-m-qty>1</span><button type="button" data-qty-plus aria-label="Increase">+</button></div>' +
    '    </div>' +
    '    <button class="btn gold pmodal__add" type="button" data-add><span>Add to Bag</span></button>' +
    '    <div class="pmodal__copy" data-m-body></div>' +
    '    <ul class="pmodal__details" data-m-details></ul>' +
    '  </div>' +
    '</div>';
  document.body.appendChild(overlay);

  var drawer = el("aside", "bag-drawer");
  drawer.setAttribute("aria-label", "Shopping bag");
  drawer.innerHTML =
    '<div class="bag-drawer__head"><h3>Your Bag</h3><button class="pmodal__close" type="button" data-bag-close aria-label="Close bag">&times;</button></div>' +
    '<div class="bag-drawer__items" data-bag-items></div>' +
    '<div class="bag-drawer__foot">' +
    '  <p class="bag-drawer__total">Subtotal <b data-bag-total>$0.00</b></p>' +
    '  <a class="btn gold" data-bag-checkout href="#"><span data-bag-checkout-label>Email Your Order</span></a>' +
    '  <p class="pmodal__note" data-bag-note>Email your order and our team will confirm availability, payment, and pickup or shipping.</p>' +
    '</div>';
  document.body.appendChild(drawer);

  var bagBtn = el("button", "bag-fab");
  bagBtn.type = "button";
  bagBtn.setAttribute("aria-label", "Open shopping bag");
  bagBtn.innerHTML =
    '<svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1.5"><path d="M6 8h12l-1 13H7L6 8Z"/><path d="M9 8V6a3 3 0 0 1 6 0v2"/></svg>' +
    '<span class="bag-fab__count" data-bag-count hidden>0</span>';
  document.body.appendChild(bagBtn);

  /* ---------- Product modal ---------- */
  var current = null, qty = 1, selects = [];
  var mImg = overlay.querySelector(".pmodal__main img");
  var mThumbs = overlay.querySelector("[data-m-thumbs]");
  var mTag = overlay.querySelector("[data-m-tag]");
  var mName = overlay.querySelector("[data-m-name]");
  var mOpts = overlay.querySelector("[data-m-opts]");
  var mBody = overlay.querySelector("[data-m-body]");
  var mDetails = overlay.querySelector("[data-m-details]");
  var mQty = overlay.querySelector("[data-m-qty]");
  var mSubtotal = overlay.querySelector("[data-m-subtotal]");
  var mAdd = overlay.querySelector("[data-add]");

  function chosen() {
    return selects.map(function (s, i) { return current.options[i].values[s.selectedIndex]; });
  }
  function unitPrice() {
    var p = current.price;
    chosen().forEach(function (v) { if (v && v.p != null) p = v.p; });
    return p;
  }
  function soldOut() { return chosen().some(function (v) { return v && v.out; }); }
  function refresh() {
    mQty.textContent = qty;
    mSubtotal.textContent = money(unitPrice() * qty);
    var out = soldOut();
    mAdd.disabled = out;
    mAdd.querySelector("span").textContent = out ? "Sold Out" : "Add to Bag";
  }
  function showImage(src) {
    mImg.src = src;
    mThumbs.querySelectorAll("button").forEach(function (b) {
      b.classList.toggle("is-on", b.getAttribute("data-src") === src);
    });
  }

  function openModal(slug) {
    current = CATALOG[slug];
    if (!current) return;
    qty = 1;
    mImg.alt = current.title;
    mTag.textContent = current.collectionName;
    mName.textContent = current.title;

    mThumbs.innerHTML = "";
    if (current.images.length > 1) {
      current.images.forEach(function (src, i) {
        var b = el("button");
        b.type = "button";
        b.setAttribute("data-src", src);
        b.setAttribute("aria-label", "Photo " + (i + 1));
        var im = el("img"); im.src = src; im.alt = ""; im.loading = "lazy";
        b.appendChild(im);
        b.addEventListener("click", function () { showImage(src); });
        mThumbs.appendChild(b);
      });
    }
    showImage(current.images[0] || current.card);

    mOpts.innerHTML = "";
    selects = current.options.map(function (o) {
      var wrap = el("div", "pmodal__field");
      var id = "opt-" + Math.random().toString(36).slice(2, 8);
      var lab = el("label", null, o.name); lab.htmlFor = id;
      var sel = el("select"); sel.id = id;
      o.values.forEach(function (v) {
        var opt = el("option", null, v.v + (v.p != null && current.low !== current.high ? "  ·  " + money(v.p) : "") + (v.out ? " (sold out)" : ""));
        sel.appendChild(opt);
      });
      var first = o.values.findIndex(function (v) { return !v.out; });
      sel.selectedIndex = Math.max(0, first);
      sel.addEventListener("change", refresh);
      wrap.appendChild(lab); wrap.appendChild(sel);
      mOpts.appendChild(wrap);
      return sel;
    });

    mBody.innerHTML = "";
    current.body.forEach(function (p) { mBody.appendChild(el("p", null, p)); });
    mDetails.innerHTML = "";
    current.details.forEach(function (d) { mDetails.appendChild(el("li", null, d)); });

    refresh();
    overlay.classList.add("open");
    document.body.style.overflow = "hidden";
    overlay.querySelector(".pmodal").scrollTop = 0;
  }
  function closeModal() {
    overlay.classList.remove("open");
    document.body.style.overflow = "";
  }

  document.querySelectorAll(".product").forEach(function (card) {
    var buy = card.querySelector("[data-product]");
    if (!buy) return;
    var slug = buy.getAttribute("data-product");
    var open = function () { openModal(slug); };
    [card.querySelector(".product__media"), card.querySelector(".product__name")].forEach(function (n) {
      if (!n) return;
      n.style.cursor = "pointer";
      n.addEventListener("click", open);
    });
    var btn = card.querySelector("[data-open-product]");
    if (btn) btn.addEventListener("click", open);
  });

  overlay.addEventListener("click", function (e) { if (e.target.closest("[data-close]")) closeModal(); });
  overlay.querySelector("[data-qty-minus]").addEventListener("click", function () { qty = Math.max(1, qty - 1); refresh(); });
  overlay.querySelector("[data-qty-plus]").addEventListener("click", function () { qty = Math.min(20, qty + 1); refresh(); });
  document.addEventListener("keydown", function (e) { if (e.key === "Escape") { closeModal(); closeBag(); } });

  mAdd.addEventListener("click", function () {
    if (soldOut()) return;
    var vals = chosen().map(function (v) { return v.v; });
    var variant = vals.join(" / ");
    var items = readBag();
    var match = items.find(function (i) { return i.slug === current.handle && i.variant === variant; });
    if (match) { match.qty = Math.min(20, match.qty + qty); }
    else {
      items.push({ slug: current.handle, name: current.title, variant: variant, options: vals,
        price: unitPrice(), img: current.card, qty: qty });
    }
    writeBag(items);
    closeModal();
    openBag();
  });

  /* ---------- Bag drawer ---------- */
  var itemsEl = drawer.querySelector("[data-bag-items]");
  var totalEl = drawer.querySelector("[data-bag-total]");
  var checkoutEl = drawer.querySelector("[data-bag-checkout]");
  var checkoutLabel = drawer.querySelector("[data-bag-checkout-label]");
  var noteEl = drawer.querySelector("[data-bag-note]");
  var countEl = bagBtn.querySelector("[data-bag-count]");
  var shopify = function () { return window.CavalliShopify && window.CavalliShopify.enabled; };

  function renderBadge() {
    var n = readBag().reduce(function (a, i) { return a + i.qty; }, 0);
    countEl.textContent = n;
    countEl.hidden = n === 0;
  }
  function renderBag() {
    var items = readBag();
    itemsEl.innerHTML = "";
    if (!items.length) {
      itemsEl.appendChild(el("p", "bag-empty", "Your bag is empty. The fields are waiting."));
    }
    items.forEach(function (i, idx) {
      var row = el("div", "bag-item");
      var im = el("img"); im.src = i.img; im.alt = "";
      var info = el("div", "bag-item__info");
      info.appendChild(el("b", null, i.name));
      if (i.variant) info.appendChild(el("span", "bag-item__variant", i.variant));
      var q = el("div", "qty qty--sm");
      q.innerHTML = '<button type="button" data-i="' + idx + '" data-dec aria-label="Decrease">&minus;</button><span>' + i.qty +
        '</span><button type="button" data-i="' + idx + '" data-inc aria-label="Increase">+</button>';
      info.appendChild(q);
      var end = el("div", "bag-item__end");
      end.appendChild(el("span", null, money(i.price * i.qty)));
      var rm = el("button", "bag-item__remove", "Remove"); rm.type = "button";
      rm.setAttribute("data-i", idx); rm.setAttribute("data-remove", "");
      end.appendChild(rm);
      row.appendChild(im); row.appendChild(info); row.appendChild(end);
      itemsEl.appendChild(row);
    });
    var total = items.reduce(function (a, i) { return a + i.price * i.qty; }, 0);
    totalEl.textContent = money(total);

    if (shopify()) {
      checkoutLabel.textContent = "Checkout";
      noteEl.textContent = "Secure checkout by Shopify. Shipping and tax are calculated at checkout.";
      checkoutEl.href = "#";
    } else {
      checkoutLabel.textContent = "Email Your Order";
      noteEl.textContent = "Email your order and our team will confirm availability, payment, and pickup or shipping.";
      var lines = items.map(function (i) {
        return i.qty + " x " + i.name + (i.variant ? " (" + i.variant + ")" : "") + " - " + money(i.price * i.qty);
      });
      var body = "Hello Cavalli Estates,\r\n\r\nI would like to place an order:\r\n\r\n" + lines.join("\r\n") +
        "\r\n\r\nSubtotal: " + money(total) + "\r\n\r\nName:\r\nPhone:\r\nPickup or shipping:\r\n\r\nThank you!";
      checkoutEl.href = "mailto:" + ORDER_EMAIL + "?subject=" + encodeURIComponent("Cavalli Lavender Shop Order") +
        "&body=" + encodeURIComponent(body);
    }
    checkoutEl.classList.toggle("is-disabled", !items.length);
    renderBadge();
  }
  function openBag() { renderBag(); drawer.classList.add("open"); }
  function closeBag() { drawer.classList.remove("open"); }

  checkoutEl.addEventListener("click", function (e) {
    var items = readBag();
    if (!items.length) { e.preventDefault(); return; }
    if (!shopify()) return;
    e.preventDefault();
    checkoutLabel.textContent = "Opening checkout…";
    window.CavalliShopify.checkout(items).then(function (url) {
      window.location.href = url;
    }).catch(function (err) {
      checkoutLabel.textContent = "Checkout";
      noteEl.textContent = "Checkout could not open (" + err.message + "). Please try again, or call 805-242-1154.";
    });
  });

  bagBtn.addEventListener("click", function () {
    if (drawer.classList.contains("open")) closeBag(); else openBag();
  });
  drawer.addEventListener("click", function (e) {
    if (e.target.closest("[data-bag-close]")) { closeBag(); return; }
    var btn = e.target.closest("button[data-i]");
    if (!btn) return;
    var items = readBag();
    var i = parseInt(btn.getAttribute("data-i"), 10);
    if (btn.hasAttribute("data-inc")) items[i].qty = Math.min(20, items[i].qty + 1);
    if (btn.hasAttribute("data-dec")) items[i].qty = Math.max(1, items[i].qty - 1);
    if (btn.hasAttribute("data-remove")) items.splice(i, 1);
    writeBag(items);
    renderBag();
  });

  renderBadge();
})();
