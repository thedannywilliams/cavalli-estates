/* ============================================================
   Cavalli Estates: Shop bag & product detail
   ------------------------------------------------------------
   Product data comes from <script id="shop-catalog"> in shop.html,
   generated by shop-data/build_shop.py. Cards open a detail view
   (photos, options, quantity); Add to Bag keeps a cart in
   localStorage. Checkout goes to Shopify when js/shop.js is
   configured, otherwise the bag is emailed to the estate.
   ============================================================ */
